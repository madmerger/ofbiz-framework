import json
import tempfile
import unittest
from pathlib import Path

from ofbiz2spring import PACKAGE_PATH, generate, java_name_to_db_name


REPO_ROOT = Path(__file__).resolve().parents[2]
INVENTORY_PATH = REPO_ROOT / "docs/migration/humanres/inventory/inventory.json"


class Ofbiz2SpringTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.inventory = json.loads(INVENTORY_PATH.read_text(encoding="utf-8"))

    def test_generates_all_humanres_entities_repositories_and_service_catalog(self):
        with tempfile.TemporaryDirectory() as temp_dir:
            java_root = Path(temp_dir)
            generated = generate(self.inventory, java_root)
            package_dir = java_root / PACKAGE_PATH
            entity_count = len(self.inventory["entities"])
            service_count = sum(
                service["engine"] == "entity-auto"
                for service in self.inventory["services"]
            )

            self.assertEqual(entity_count, 41)
            self.assertEqual(service_count, 121)
            self.assertEqual(entity_count * 2 + 2, len(generated))
            self.assertTrue((package_dir / "PartyQual.java").exists())
            self.assertTrue((package_dir / "PartyQualRepository.java").exists())
            catalog = (package_dir / "ServiceCatalog.java").read_text(encoding="utf-8")
            self.assertEqual(service_count, catalog.count("services.put("))
            self.assertIn("createPartyQual", catalog)
            self.assertIn("GENERATED by ofbiz2spring — do not edit", catalog)

    def test_generates_composite_ids_types_columns_and_stamp_callbacks(self):
        with tempfile.TemporaryDirectory() as temp_dir:
            package_dir = Path(temp_dir) / PACKAGE_PATH
            generate(self.inventory, Path(temp_dir))
            party_qual = (package_dir / "PartyQual.java").read_text(encoding="utf-8")
            self.assertIn("@IdClass(PartyQual.EntityId.class)", party_qual)
            self.assertIn('@Column(name = "PARTY_ID", length = 20, nullable = false)', party_qual)
            self.assertIn("public static class EntityId implements Serializable", party_qual)
            self.assertIn("private Timestamp fromDate;", party_qual)
            stamps = (package_dir / "StampFields.java").read_text(encoding="utf-8")
            self.assertIn('@Column(name = "CREATED_TX_STAMP")', stamps)
            self.assertIn("@PrePersist", stamps)
            self.assertIn("@PreUpdate", stamps)

    def test_converts_ofbiz_camel_case_table_and_column_names(self):
        self.assertEqual("EMPL_POSITION", java_name_to_db_name("EmplPosition"))
        self.assertEqual("PARTY_ID_FROM", java_name_to_db_name("partyIdFrom"))


if __name__ == "__main__":
    unittest.main()
