#!/usr/bin/env python3
"""Generate migration ECA resources and the reviewable coverage inventory."""

import argparse
from collections import Counter
import json
from pathlib import Path
import re

from ofbiz_inventory import parse_xml, parse_entitymodel, parse_service_file

ROOT = Path(__file__).resolve().parents[2]
COMPONENTS = 'accounting commonext content humanres manufacturing marketing order party product workeffort'.split()
SUPPORTED = {'condition', 'condition-field', 'condition-service', 'and', 'or', 'xor', 'not', 'action', 'set'}


def node(element):
    return {'tag': element.tag, 'attributes': dict(element.attrib), 'children': [node(c) for c in element]}


def generate(disabled):
    fields = {}
    for path in sorted(ROOT.glob('**/entitydef/*entitymodel*.xml')):
        if 'build' not in path.parts:
            entities, _ = parse_entitymodel(ROOT, path)
            fields.update({e['name']: {f['name']: f for f in e['fields']} for e in entities})
    services = {}
    for parent in ['framework', 'applications']:
        for path in sorted((ROOT / parent).glob('*/servicedef/*.xml')):
            xml, _ = parse_xml(path)
            overrides = {s.get('name'): {p.get('name'): p.get('mode') for p in s.findall('override')
                                      if p.get('mode')} for s in xml.iter('service')}
            for service in parse_service_file(ROOT, path, fields):
                service['override_modes'] = overrides.get(service['name'], {})
                services[service['name']] = service
    source = '\n'.join(p.read_text() for c in COMPONENTS
                       for p in (ROOT / 'migration' / (c + '-springboot') / 'src/main/java').rglob('*.java'))
    quoted = set(re.findall(r'"([A-Za-z][A-Za-z0-9]*)"', source))
    ported = {name for name, s in services.items()
              if name in quoted or (s['engine'] == 'entity-auto' and s['source'].split('/')[1] in COMPONENTS)}
    params = {}

    def parameters(name, visiting=()):
        if name in params:
            return params[name]
        if name not in services or name in visiting:
            return {}
        service = services[name]
        result = {p['name']: p.get('mode') for p in service['params']}
        for inherited in service.get('implements', []):
            for field, mode in parameters(inherited['service'], (*visiting, name)).items():
                existing = result.get(field)
                result[field] = 'INOUT' if existing and existing != mode else mode
        result = {field: mode or 'IN' for field, mode in result.items()}
        result.update(service['override_modes'])
        params[name] = result
        return result

    rules = []
    for component in COMPONENTS:
        descriptor, _ = parse_xml(ROOT / 'applications' / component / 'ofbiz-component.xml')
        for resource in descriptor:
            if resource.get('type') != 'eca':
                continue
            path = ROOT / 'applications' / component / resource.get('location')
            tree, lines = parse_xml(path)
            for ordinal, element in enumerate(tree.findall('eca'), 1):
                rule = node(element)
                rule.update(id=f'{component}/{resource.get("location")}#{ordinal}', component=component,
                            kind='service' if resource.tag == 'service-resource' else 'entity',
                            source=f'{path.relative_to(ROOT)}:{lines[id(element)]}')
                rule['disabledReason'] = disabled.get(rule['id'], '')
                conditions = [c for c in element.iter() if c.tag not in {'eca', 'action', 'set'}]
                unsupported = any(c.tag not in SUPPORTED or (c.tag == 'condition-service'
                                  and c.get('service-name') not in ported) for c in conditions)
                actions = [a.get('service') for a in element.findall('action')]
                rule['status'] = ('disabled-hand-wired' if rule['disabledReason'] else
                                  'unsupported-condition' if unsupported else
                                  'target-unported' if not any(a in ported for a in actions) else 'active')
                rules.append(rule)
    unknown = set(disabled) - {r['id'] for r in rules}
    if unknown:
        raise ValueError(f'Unknown disabled rule IDs: {sorted(unknown)}')
    for name in services:
        parameters(name)
    return {'rules': rules, 'parameters': params, 'portedCandidates': sorted(ported)}


def report(catalog):
    lines = ['# Migration ECA coverage', '', 'Generated by `migration/tools/eca_catalog.py`; do not edit.', '',
             'IDs use component/resource/one-based XML rule ordinal (comments excluded).',
             'Active means supported with at least one statically ported target; runtime registration is authoritative.',
             'Each action is checked independently. Unregistered targets are skipped and counted at runtime.',
             'Entity rules cover entity-auto operations; direct JPA/repository writes are not intercepted.', '',
             '| Component | Active | Disabled hand-wired | Target unported | Unsupported condition | Total |',
             '|---|---:|---:|---:|---:|---:|']
    for component in COMPONENTS:
        counts = Counter(r['status'] for r in catalog['rules'] if r['component'] == component)
        values = [counts[s] for s in ['active', 'disabled-hand-wired', 'target-unported', 'unsupported-condition']]
        lines.append(f'| {component} | ' + ' | '.join(map(str, [*values, sum(values)])) + ' |')
    lines += ['', '| Rule ID / source | Kind | Trigger | Event / operation | Actions | Status / reason |',
              '|---|---|---|---|---|---|']
    for rule in catalog['rules']:
        a = rule['attributes']
        targets = [c['attributes']['service'] for c in rule['children'] if c['tag'] == 'action']
        targets = [t + (' (unported)' if t not in catalog['portedCandidates'] else '') for t in targets]
        lines.append(f'| `{rule["id"]}`<br>{rule["source"]} | {rule["kind"]} | '
                     f'{a.get("service", a.get("entity"))} | {a["event"]} {a.get("operation", "")} | '
                     + ', '.join(targets) + f' | {rule["status"]} {rule["disabledReason"]} |')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--coverage', type=Path, required=True)
    parser.add_argument('--disabled', type=Path, required=True)
    args = parser.parse_args()
    catalog = generate(json.loads(args.disabled.read_text()))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(catalog, indent=2) + '\n')
    args.coverage.write_text(report(catalog))
    print(f'Generated {len(catalog["rules"])} ECA rules')
