def java_name_to_db_name(name: str) -> str:
    """Match OFBiz ModelUtil.javaNameToDbName for camel-case names."""
    return re.sub(r"(?<!^)([A-Z])", r"_\1", name).upper()


def java_identifier(name: str) -> str:
    safe = re.sub(r"\W", "_", name)
    if not safe or safe[0].isdigit():
        safe = "_" + safe
    return safe + "_" if safe in JAVA_KEYWORDS else safe


def java_string(value: Any) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def field_mapping(field: dict[str, Any]) -> dict[str, Any]:
    try:
        return TYPE_MAPPING[field["type"]]
    except KeyError as error:
        raise ValueError(f"Unsupported OFBiz field type: {field['type']}") from error


def column_name(field: dict[str, Any]) -> str:
    return field.get("column") or java_name_to_db_name(field["name"])


def imports_for(entity: dict[str, Any]) -> list[str]:
    imports = {
        "jakarta.persistence.Column",
        "jakarta.persistence.Entity",
        "jakarta.persistence.Table",
        "java.sql.Timestamp",
    }
    if len([field for field in entity["fields"] if field["pk"]]) > 1:
        imports.update(
            {
                "jakarta.persistence.IdClass",
                "java.io.Serializable",
                "java.util.Objects",
            }
        )
    java_types = {field_mapping(field)["java_type"] for field in entity["fields"]}
    if "BigDecimal" in java_types:
        imports.add("java.math.BigDecimal")
    if "Date" in java_types:
        imports.add("java.sql.Date")
    if "Time" in java_types:
        imports.add("java.sql.Time")
    if any(field_mapping(field).get("lob") for field in entity["fields"]):
        imports.add("jakarta.persistence.Lob")
    return sorted(imports)


def column_annotation(field: dict[str, Any]) -> list[str]:
    mapping = field_mapping(field)
    attributes = [f"name = {java_string(column_name(field))}"]
    if mapping.get("length") is not None:
        attributes.append(f"length = {mapping['length']}")
    if mapping.get("precision") is not None:
        attributes.append(f"precision = {mapping['precision']}")
        attributes.append(f"scale = {mapping['scale']}")
    if field["pk"]:
        attributes.append("nullable = false")
    if mapping.get("column_definition"):
        attributes.append(f"columnDefinition = {java_string(mapping['column_definition'])}")
    return [
        "@Lob" if mapping.get("lob") else "",
        f"@Column({', '.join(attributes)})",
    ]


def getter_setter(java_type: str, name: str) -> str:
    method_suffix = name[0].upper() + name[1:]
    return (
        f"    public {java_type} get{method_suffix}() {{ return {name}; }}\n"
        f"    public void set{method_suffix}({java_type} {name}) {{ this.{name} = {name}; }}"
    )


def entity_source(entity: dict[str, Any], package_name: str = PACKAGE) -> str:
    class_name = entity["name"]
    fields = entity["fields"]
    pk_fields = [field for field in fields if field["pk"]]
    imports = "\n".join(f"import {item};" for item in imports_for(entity))
    lines = [
        HEADER,
        f"package {package_name};",
        "",
        imports,
        "",
        "@Entity",
        f"@Table(name = {java_string(entity['table'])})",
    ]
    if len(pk_fields) > 1:
        lines.append(f"@IdClass({class_name}.EntityId.class)")
    lines.extend(
        [
            f"public class {class_name} extends StampFields {{",
            f"    public {class_name}() {{}}",
            "",
        ]
    )
    for field in fields:
        name = java_identifier(field["name"])
        java_type = field_mapping(field)["java_type"]
        lines.extend(f"    {annotation}" for annotation in column_annotation(field) if annotation)
        if field["pk"]:
            lines.append("    @jakarta.persistence.Id")
        lines.append(f"    private {java_type} {name};")
        lines.append("")
    for field in fields:
        name = java_identifier(field["name"])
        lines.append(getter_setter(field_mapping(field)["java_type"], name))
        lines.append("")
    if len(pk_fields) > 1:
        lines.extend(id_class_source(pk_fields, class_name))
    lines.append("}")
